for relative in ['src/App.tsx', 'src/data/ornament.ts', 'index.html']:
    path = root / relative
    text = path.read_text(encoding='utf-8')
    for original in sorted(originals, key=len, reverse=True):
        latin = ''.join(mapping.get(c, c) for c in original)
        text = text.replace(latin, original)
    text = text.replace('lang="kk-Latn"', 'lang="kk"')
    path.write_text(text, encoding='utf-8', newline='\n')
